def _authored_box(tmp_path: Path) -> bytes:
    path = tmp_path / "source.step"
    write_step(native_solid("box"), path)
    text = path.read_text()
    faces = re.findall(r"#(\d+)=ADVANCED_FACE\('',", text)
    solid = re.search(r"#(\d+)=MANIFOLD_SOLID_BREP\('',", text)
    assert solid is not None
    text = text.replace(
        f"#{faces[0]}=ADVANCED_FACE('',", f"#{faces[0]}=ADVANCED_FACE('inlet',"
    )
    text = text.replace(
        f"#{faces[1]}=ADVANCED_FACE('',", f"#{faces[1]}=ADVANCED_FACE('wall',"
    )
    text = text.replace(
        f"#{solid[1]}=MANIFOLD_SOLID_BREP('',", f"#{solid[1]}=MANIFOLD_SOLID_BREP('body',"
    )
    maximum = max(int(value) for value in re.findall(r"#(\d+)=", text))
    # This chain is handwritten from the STEP surface-fill relationships, not
    # generated by the implementation's presentation writer.
    records = [
        "COLOUR_RGB('red',1.,0.,0.)",
        f"FILL_AREA_STYLE_COLOUR('',#{maximum + 1})",
        f"FILL_AREA_STYLE('',(#{maximum + 2}))",
        f"SURFACE_STYLE_FILL_AREA(#{maximum + 3})",
        f"SURFACE_SIDE_STYLE('',(#{maximum + 4}))",
        f"SURFACE_STYLE_USAGE(.BOTH.,#{maximum + 5})",
        f"PRESENTATION_STYLE_ASSIGNMENT((#{maximum + 6}))",
        f"STYLED_ITEM('',(#{maximum + 7}),#{solid[1]})",
        f"PRESENTATION_LAYER_ASSIGNMENT('fluid','',({','.join('#' + face for face in faces)}))",
    ]
    extra = "".join(f"#{maximum + i}={record};\n" for i, record in enumerate(records, 1))
    return text.replace("ENDSEC;\nEND-ISO", extra + "ENDSEC;\nEND-ISO").encode()


def test_handwritten_names_body_color_and_layer(tmp_path: Path) -> None:
    result = decode_step_bytes(_authored_box(tmp_path), POLICY)
    metadata = result.entity_metadata
    assert metadata is not None
    assert metadata.entities("name", "inlet") == (result.model.face_ids[0],)
    assert metadata.entities("name", "body") == (result.model.solid_ids[0],)
    assert metadata.entities("color", (1.0, 0.0, 0.0)) == (result.model.solid_ids[0],)
    assert metadata.entities("layer", "fluid") == result.model.face_ids
    assert select_step_entities(result.model, metadata, "name", "inlet").selected == (
        result.model.face_ids[0],
    )
    assert (
        select_step_entities(result.model, metadata, "color", (1.0, 0.0, 0.0)).selected
        == result.model.face_ids
    )


def test_export_import_preserves_all_labels(tmp_path: Path) -> None:
    result = decode_step_bytes(_authored_box(tmp_path), POLICY)
    metadata = result.entity_metadata
    assert metadata is not None
    path = tmp_path / "labels.step"
    write_step(result.model, path, metadata=metadata)
    reread = decode_step_bytes(path.read_bytes(), POLICY)
    assert reread.entity_metadata is not None
    before = [
        (row.entity.kind, row.entity.index, row.names, row.colors, row.layers)
        for row in metadata.rows
    ]
    after = [
        (row.entity.kind, row.entity.index, row.names, row.colors, row.layers)
        for row in reread.entity_metadata.rows
    ]
    assert after == before


def test_duplicate_authored_names_report_every_conflict(tmp_path: Path) -> None:
    data = _authored_box(tmp_path).replace(
        b"ADVANCED_FACE('wall',", b"ADVANCED_FACE('inlet',"
    )
    result = decode_step_bytes(data, POLICY)
    metadata = result.entity_metadata
    assert metadata is not None
    with pytest.raises(StepMetadataConflict) as caught:
        select_step_entities(result.model, metadata, "name", "inlet")
    assert caught.value.entities == result.model.face_ids[:2]


def test_metadata_attachment_never_changes_model_identity(tmp_path: Path) -> None:
    imported = decode_step_bytes(_authored_box(tmp_path), POLICY)
    model = imported.model
    identity = model.model_id
    revision = model.source_revision
    before = model.face_ids
    first = StepEntityMetadata(model, (StepEntityLabels(before[0], names=("inlet",)),))
    second = StepEntityMetadata(model, (StepEntityLabels(before[0], names=("outlet",)),))
    assert first.metadata_id != second.metadata_id
    changed = replace(imported, entity_metadata=second)
    assert changed.model.model_id == imported.model.model_id
    assert changed.model.face_ids == imported.model.face_ids
    assert changed.result_id != imported.result_id
    assert model.model_id == identity
    assert model.source_revision == revision
    assert model.face_ids == before


def test_source_label_edits_retain_whole_file_revision_identity(tmp_path: Path) -> None:
    original = _authored_box(tmp_path)
    before = decode_step_bytes(original, POLICY).model
    after = decode_step_bytes(original.replace(b"'inlet'", b"'outlet'"), POLICY).model
    assert before.source_revision != after.source_revision
    assert before.model_id != after.model_id
    assert before.geometry is not None and after.geometry is not None
    assert before.geometry.geometry_id == after.geometry.geometry_id


def test_multiple_names_round_trip(tmp_path: Path) -> None:
    model = native_solid("box")
    metadata = StepEntityMetadata(
        model, (StepEntityLabels(model.solid_ids[0], names=("body", "product")),)
    )
    path = tmp_path / "aliases.step"
    write_step(model, path, metadata=metadata)
