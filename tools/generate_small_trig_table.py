"""Emit meshcore's small-angle constants, certified by rational Taylor bounds."""

from fractions import Fraction


_SCALE = 128
_LAST_ANCHOR = 200
_TERMS = 24


def _trigonometric_bounds(x: Fraction, first_degree: int) -> tuple[Fraction, Fraction]:
    # At 0 <= x <= 25/16, the terms decrease from the first term after
    # the quadratic term. Truncating at _TERMS brackets the alternating tail.
    square = x * x
    term = x**first_degree
    total = term
    for index in range(1, _TERMS):
        degree = first_degree + 2 * index
        term *= -square / (degree * (degree - 1))
        total += term
    degree = first_degree + 2 * _TERMS
    alternate = total - term * square / (degree * (degree - 1))
    return min(total, alternate), max(total, alternate)


def _double_word(lower: Fraction, upper: Fraction) -> str:
    high = float(lower)
    if high != float(upper):
        raise ArithmeticError("Taylor bounds do not determine the high word.")
    high_exact = Fraction(high)
    low = float(lower - high_exact)
    if low != float(upper - high_exact):
        raise ArithmeticError("Taylor bounds do not determine the low word.")
    return f"{{{high.hex()}, {low.hex()}}}"


def main() -> None:
    print("// Copyright © 2026 PHYDRA, Inc. All rights reserved.")
    print("// Generated by tools/generate_small_trig_table.py.")
    print()
    print("#pragma once")
    print()
    print('#include "elementary.hpp"')
    print()
    print("namespace phx::mc::elementary::constants {")
    print()
    print(f"inline constexpr double kSmallTrigScale = {_SCALE}.0;")
    limit = float(Fraction(_LAST_ANCHOR, _SCALE)).hex()
    print(f"inline constexpr double kSmallTrigLimit = {limit};")
    print()
    print("struct SmallTrigAnchor {")
    print("  DoubleWord sine;")
    print("  DoubleWord cosine;")
    print("};")
    print("inline constexpr SmallTrigAnchor kSmallTrigAnchors[] = {")
    for index in range(_LAST_ANCHOR + 1):
        x = Fraction(index, _SCALE)
        sine = _double_word(*_trigonometric_bounds(x, 1))
        cosine = _double_word(*_trigonometric_bounds(x, 0))
        print(f"    {{{sine},\n     {cosine}}},")
    print("};")
    print()
    print("}  // namespace phx::mc::elementary::constants")


if __name__ == "__main__":
    main()
