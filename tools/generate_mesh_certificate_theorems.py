"""Generate the mesh certificate register from selectors and owner docstrings."""

from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path

from phydrax.geometry._mesh_theorems import (
    generate_mesh_certificate_theorem_records,
    MeshCertificateTheorem,
)


ROOT = Path(__file__).resolve().parents[1]
SELECTOR = Path("phydrax/geometry/_mesh_check_names.py")
REGISTER = Path("phydrax/geometry/_mesh_theorem_register.json")
DOCUMENTATION = Path("docs/api/mesh_certificate_theorems.md")
SOURCE_ROOTS = ("phydrax/geometry", "phydrax/meshing")


def _closed_checks(tree: ast.Module, /) -> tuple[str, ...]:
    for node in tree.body:
        match node:
            case ast.TypeAlias(name=ast.Name(id="MeshCertificateCheck"), value=value):
                selector = value
            case ast.AnnAssign(
                target=ast.Name(id="MeshCertificateCheck"), value=value
            ) if value is not None:
                selector = value
            case _:
                continue
        if not isinstance(selector, ast.Subscript):
            raise ValueError(
                "MeshCertificateCheck.declaration must be a Literal selector; got a non-subscript declaration"
            )
        match selector.value:
            case ast.Name(id="Literal") | ast.Attribute(attr="Literal"):
                pass
            case _:
                raise ValueError(
                    "MeshCertificateCheck.declaration must use Literal; got another selector expression"
                )
        nodes = (
            selector.slice.elts
            if isinstance(selector.slice, ast.Tuple)
            else [selector.slice]
        )
        checks = []
        for member in nodes:
            match member:
                case ast.Constant(value=str() as name):
                    checks.append(name)
                case _:
                    raise ValueError(
                        "MeshCertificateCheck.members must contain literal strings; got another expression"
                    )
        if len(set(checks)) != len(checks):
            raise ValueError(
                "MeshCertificateCheck.members must be unique; got duplicate check names"
            )
        return tuple(checks)
    raise ValueError("MeshCertificateCheck.declaration must exist; got no selector")


def _docstrings(
    node: ast.AST,
    owner: str,
    documents: list[tuple[str, str]],
    symbols: set[str],
    /,
) -> None:
    match node:
        case ast.Module() | ast.ClassDef() | ast.FunctionDef() | ast.AsyncFunctionDef():
            symbols.add(owner)
            docstring = ast.get_docstring(node)
            if docstring is not None:
                documents.append((owner, docstring))
        case _:
            pass
    for child in ast.iter_child_nodes(node):
        match child:
            case (
                ast.ClassDef(name=name)
                | ast.FunctionDef(name=name)
                | ast.AsyncFunctionDef(name=name)
            ):
                _docstrings(child, f"{owner}.{name}", documents, symbols)
            case _:
                _docstrings(child, owner, documents, symbols)


def _records(root: Path, /) -> tuple[MeshCertificateTheorem, ...]:
    checks = _closed_checks(
        ast.parse(
            (root / SELECTOR).read_text(encoding="utf-8"), filename=str(root / SELECTOR)
        )
    )
    documents: list[tuple[str, str]] = []
    symbols: set[str] = set()
    for source_root in SOURCE_ROOTS:
        for path in sorted((root / source_root).rglob("*.py")):
            owner = ".".join(path.relative_to(root).with_suffix("").parts)
            _docstrings(
                ast.parse(path.read_text(encoding="utf-8"), filename=str(path)),
                owner,
                documents,
                symbols,
            )
    records = generate_mesh_certificate_theorem_records(checks, tuple(documents))
    for record in records:
        for contract in record.contracts:
            if contract.owner not in symbols:
                raise ValueError(
                    "MeshCertificateCheckContract.owner must identify a declared source "
                    f"symbol; got {contract.owner!r} for check {record.check!r}"
                )
    return records


def _markdown(records: tuple[MeshCertificateTheorem, ...], /) -> str:
    lines = [
        "# Mesh certificate theorem register",
        "",
        "Generated by `tools/generate_mesh_certificate_theorems.py` from",
        f"`{SELECTOR.as_posix()}` and structured check metadata in the cited source docstrings.",
        "",
        "N denotes a certified numerical bound; X denotes a combinatorial or identity",
        "predicate; T denotes an external topology result. A definition citation states",
        "an administrative contract rather than a topological implication. Each check",
        "retains separate contracts when several consumers document different implications.",
        "Failure statuses preserve finding outcomes and route refusals. In particular,",
        "`premise_unproven` declines the boundary-degree route while allowing another",
        "proof to certify the mesh; it is not an unresolved mesh-certificate finding.",
        "An empty list denotes a success obligation recorded after its hypotheses hold.",
        "Coverage applies to the closed `MeshCertificateCheck` finding/obligation selector,",
        "not arbitrary descriptive strings in a certificate's `evaluated_checks` field.",
        "",
        f"Closed checks: {len(records)}.",
        "",
    ]
    for record in records:
        lines.extend(
            (
                f"## `{record.check}`",
                "",
                "Failure statuses: "
                + (
                    ", ".join(f"`{status}`" for status in record.failure_statuses)
                    or "none (success obligation)"
                ),
                "",
            )
        )
        for contract in record.contracts:
            lines.extend(
                (
                    f"### `{contract.owner}`",
                    "",
                    f"Documentation: `{contract.documentation_owner}`.",
                    "",
                    "Hypotheses:",
                    "",
                )
            )
            lines.extend(
                f"- **{premise.tag}** — {premise.statement}"
                for premise in contract.premises
            )
            citation = contract.citation
            reference = (
                f"[{citation.reference}]({citation.url})"
                if citation.url
                else citation.reference
            )
            lines.extend(
                (
                    "",
                    f"Conclusion: {contract.conclusion}",
                    "",
                    f"Citation ({citation.kind}): {reference}, {citation.locator}.",
                    "",
                    "Failure statuses for this contract: "
                    + (
                        ", ".join(f"`{status}`" for status in contract.failure_statuses)
                        or "none (success obligation)"
                    ),
                    "",
                )
            )
    return "\n".join(lines)


def main() -> int:
    """Write deterministic generated files, or report drift without modification."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    records = _records(ROOT)
    payload = {
        "selector_source": SELECTOR.as_posix(),
        "records": [record.to_record() for record in records],
    }
    rendered = {
        REGISTER: json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False)
        + "\n",
        DOCUMENTATION: _markdown(records),
    }
    drift = []
    for relative, content in rendered.items():
        path = ROOT / relative
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            drift.append(relative.as_posix())
            if not arguments.check:
                path.write_text(content, encoding="utf-8")
    if arguments.check and drift:
        print("Mesh certificate register drift:\n" + "\n".join(drift))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
