# Relative singular-value cutoff separating exactly dependent coupling families
# (rounding-level singular values) from independent ones (order-one values).
_COUPLING_RANK_RELATIVE_CUTOFF = 1.0e-10
_DEFAULT_MAXIMUM_TERMS = 1 << 16
_DEFAULT_MAXIMUM_NODES = 1 << 16
_DEFAULT_EQUIVARIANCE_TOLERANCE = 1.0e-9
# Fixed improper test transformation for basis equivariance evidence.
_EVIDENCE_ANGLES = (0.3141592653589793, 1.2345678901234567, -0.7071067811865476)
# Native-origin evidence: a restored native basis must be orthonormal and span
# the regenerated coupling span to the rank cutoff. The span is gauge-free; the
# individual singular vectors of degenerate couplings are not, so they are not
# regenerated and compared.
_NATIVE_SPAN_TOLERANCE = 1.0e-10
# Owner dense-entry budget of native basis generation and restored-basis
# replay. Generation charges its exact projection and intermediate coupling
# families before allocating them; replay charges ``terms * components * paths``
# stored routes before re-projecting them densely, instead of trusting recorded
# sizes.
_MAXIMUM_REPLAY_ENTRIES = 1 << 24


