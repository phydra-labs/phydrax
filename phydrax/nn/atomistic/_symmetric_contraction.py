"""MACE symmetric contraction with preserved W and a fixed U-to-polynomial map.

For output block ``L`` and correlation order ``nu`` the source contraction is

    B[c, M] = sum_k W_nu[species, k, c] sum_{i_1..i_nu} U_nu[M, i_1..i_nu, k]
              x[c, i_1] ... x[c, i_nu].

Only the symmetric part of ``U_nu`` contributes, so each basis is stored as its
exact projection ``P_nu[t, M, k]`` onto canonical commutative monomials ``t``.
That fixed projection is a nontrainable sparse route map; the original ``W_nu``
remain the trainable parameters. Monomials are formed once by a shared
prefix-sharing product graph, never as dense ``dim**nu`` runtime arrays.

Native bases are generated by sparse iterated real coupling of input blocks;
imported bases are the provider's exact ``U`` tensors, transformed to the native
component basis by explicit orthogonal block maps. Merged coefficients
``C = P W`` are a frozen realization bound to the numeric revision of ``W``; they
are fixed data and never become independent trainable parameters.
"""

