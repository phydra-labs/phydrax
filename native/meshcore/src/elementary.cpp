// Rigorous binary64 interval enclosures of exp, log, sin, cos, tan, atan, tanh,
// asin and acos. No libm transcendental is called: the kernels use binary64
// +, -, *, / and sqrt in round-to-nearest (RN) without contraction, the
// correctly rounded std::fma,
// and exact bit manipulation. u = 2^-53 throughout.
//
// Proof structure shared by every kernel
//  * Double-word (DW) operations carry the published relative error bounds
//    quoted at their definitions (JMP: Joldes, Muller, Popescu, ACM TOMS 44(2),
//    2017; MR: Muller, Rideau, ACM TOMS 48(1), 2022). The bounds assume no
//    underflow; every kernel below keeps its DW operands above 2^-900, or
//    states the absolute underflow error it absorbs.
//  * Horner lemma. Evaluating p(z) = sum_{n<=N} c_n z^n by s_N = c_N,
//    s_n = add(c_n, multiply(z, s_{n+1})) commits at step n an error of at
//    most 5u^2 |z s_{n+1}| + (3u^2 + 13u^3) |c_n + z s_{n+1}| <= 8.1u^2
//    (|c_n| + |z| q_{n+1}) with q_n = sum_{k>=n} |c_k| |z|^(k-n). Propagated
//    through the remaining multiplications by z, the total is at most
//    8.1u^2 (P(|z|) + |z| P'(|z|)) with P(t) = sum |c_n| t^n. The DW
//    coefficients add at most 2^-107 P(|z|).
//  * Approximation: truncated Taylor series with a Lagrange (or alternating
//    series) remainder computed analytically; the degrees and the stated
//    remainders were certified with mpmath at 300 bits.
//  * Outward rounding: a DW value v with a proven bound |f - v| <= e yields
//    [RD(h + RD(l - e)), RU(h + RU(l + e))], where RD/RU of a binary64 sum is
//    obtained exactly from the sign of the TwoSum error. Each kernel's
//    relative constant below exceeds its derived bound by the stated margin,
//    which also absorbs |f| <= |h| (1 + 2^-51).
//
// Constants (elementary.hpp) were generated by the scratch script
// gen_constants.py with mpmath at 1600 bits: every DW pair is
// (RN53(c), RN53(c - RN53(c))), 2/pi is cut into 64-bit words by repeated
// scaling and flooring, and ln 2 is split Cody-Waite style with a 42-bit head.
// The C++ tests check their algebraic consistency (normalization, the
// recurrences of the tables, (2/pi) (pi/2) = 1, tan(atan(j/16)) = j/16).
