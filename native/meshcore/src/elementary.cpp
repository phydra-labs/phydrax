// ------------------------------------------------------- DW building blocks

DoubleWord two_sum(double a, double b) noexcept {
  const double sum = a + b;
  const double a_part = sum - b;
  const double b_part = sum - a_part;
  return {sum, (a - a_part) + (b - b_part)};
}

DoubleWord two_product(double a, double b) noexcept {
  const double product = a * b;
  return {product, std::fma(a, b, -product)};
}

// JMP Algorithm 4 (DWPlusFP): relative error <= 2u^2 / (1 - 2u) < 2.01u^2.
DoubleWord add(DoubleWord x, double y) noexcept {
  const DoubleWord s = two_sum(x.high, y);
  return fast_two_sum(s.high, x.low + s.low);
}

// JMP Algorithm 6 (AccurateDWPlusDW): relative error <= 3u^2 / (1 - 4u)
// < 3u^2 + 13u^3.
DoubleWord add(DoubleWord x, DoubleWord y) noexcept {
  const DoubleWord s = two_sum(x.high, y.high);
  const DoubleWord t = two_sum(x.low, y.low);
  const DoubleWord v = fast_two_sum(s.high, s.low + t.high);
  return fast_two_sum(v.high, t.low + v.low);
}

// JMP Algorithm 9 (DWTimesFP3): relative error <= 2u^2.
DoubleWord multiply(DoubleWord x, double y) noexcept {
  const DoubleWord c = two_product(x.high, y);
  return fast_two_sum(c.high, std::fma(x.low, y, c.low));
}

// DWTimesDW with one fma (JMP Algorithm 11, published with 6u^2): relative
// error <= 5u^2 / (1 + u)^2 < 5u^2 (MR 2022, formally proved).
DoubleWord multiply(DoubleWord x, DoubleWord y) noexcept {
  const DoubleWord c = two_product(x.high, y.high);
  const double cross = std::fma(x.low, y.high, x.high * y.low);
  return fast_two_sum(c.high, c.low + cross);
}

// q1 = RN(n_h / d_h); R = n - q1 d (DWTimesFP3, then AccurateDWPlusDW);
// q2 = RN(R_h / d_h). With |q1 - n/d| <= 3.0001u |n/d|, the correction errs by
// <= 3.0001u (3.0001u + 3u^2) |n/d| and the product by 2u^2 |n/d|, so
// |q1 + q2 - n/d| <= 11.01u^2 |n/d|; Fast2Sum is exact as |q2| <= 4u |q1|.
DoubleWord divide(DoubleWord n, DoubleWord d) noexcept {
  const double first = n.high / d.high;
  const DoubleWord remainder = add(n, negate(multiply(d, first)));
  return fast_two_sum(first, remainder.high / d.high);
}

// ------------------------------------------------------- interval extensions

Enclosure exp(double lower, double upper) noexcept {
  if (std::isnan(lower) || std::isnan(upper)) return kWholeLine;
  if (lower == upper) return exp_point(lower);
  return {exp_point(lower).lower, exp_point(upper).upper};
}

Enclosure log(double lower, double upper) noexcept {
  if (std::isnan(lower) || std::isnan(upper)) return kWholeLine;
  const double low = lower <= 0.0 ? -kInfinity : log_point(lower).lower;
  const double high = upper <= 0.0 ? kInfinity : log_point(upper).upper;
  return {low, high};
}

Enclosure sin(double lower, double upper) noexcept {
  return periodic(Function::kSin, lower, upper);
}

Enclosure cos(double lower, double upper) noexcept {
  return periodic(Function::kCos, lower, upper);
}

Enclosure tan(double lower, double upper) noexcept {
  return periodic(Function::kTan, lower, upper);
}

Enclosure atan(double lower, double upper) noexcept {
  if (std::isnan(lower) || std::isnan(upper)) return kWholeLine;
  if (lower == upper) return atan_point(lower);
  return {atan_point(lower).lower, atan_point(upper).upper};
}

Enclosure tanh(double lower, double upper) noexcept {
  if (std::isnan(lower) || std::isnan(upper)) return kWholeLine;
  if (lower == upper) return tanh_point(lower);
  return {tanh_point(lower).lower, tanh_point(upper).upper};
}

// asin and acos: the box is clipped to the domain [-1, 1]; a box without a
// point in [-1, 1] gives the whole line (log's rule for an empty domain).
Enclosure asin(double lower, double upper) noexcept {
  if (std::isnan(lower) || std::isnan(upper) || upper < -1.0 || lower > 1.0) return kWholeLine;
  const double low = lower < -1.0 ? -1.0 : lower;
  const double high = upper > 1.0 ? 1.0 : upper;
  if (low == high) return asin_point(low);
  return {asin_point(low).lower, asin_point(high).upper};
}

Enclosure acos(double lower, double upper) noexcept {
  if (std::isnan(lower) || std::isnan(upper) || upper < -1.0 || lower > 1.0) return kWholeLine;
  const double low = lower < -1.0 ? -1.0 : lower;
  const double high = upper > 1.0 ? 1.0 : upper;
  if (low == high) return acos_point(low);
  return {acos_point(high).lower, acos_point(low).upper};
}

Enclosure evaluate(Function function, double lower, double upper) noexcept {
  switch (function) {
    case Function::kExp:
      return exp(lower, upper);
    case Function::kLog:
      return log(lower, upper);
    case Function::kSin:
      return sin(lower, upper);
    case Function::kCos:
      return cos(lower, upper);
    case Function::kTan:
      return tan(lower, upper);
    case Function::kAtan:
      return atan(lower, upper);
    case Function::kTanh:
      return tanh(lower, upper);
    case Function::kAsin:
      return asin(lower, upper);
    case Function::kAcos:
      return acos(lower, upper);
  }
  return kWholeLine;
}

