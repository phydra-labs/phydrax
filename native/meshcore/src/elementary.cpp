constexpr double kInfinity = std::numeric_limits<double>::infinity();
constexpr double kLargest = std::numeric_limits<double>::max();
constexpr double kSmallest = std::numeric_limits<double>::denorm_min();
constexpr std::uint64_t kMantissaMask = (std::uint64_t{1} << 52) - 1;

constexpr Enclosure kWholeLine = {-kInfinity, kInfinity};
constexpr Enclosure kUnitRange = {-1.0, 1.0};

// 2^exponent for exponent in [-1022, 1023].
double power_of_two(int exponent) noexcept {
  return std::bit_cast<double>(static_cast<std::uint64_t>(exponent + 1023) << 52);
}

DoubleWord fast_two_sum(double a, double b) noexcept {  // requires a == 0 or |a| >= |b|
  const double sum = a + b;
  return {sum, b - (sum - a)};
}

DoubleWord negate(DoubleWord x) noexcept { return {-x.high, -x.low}; }

Enclosure negate(Enclosure x) noexcept { return {-x.upper, -x.lower}; }

// RD(a + b) and RU(a + b), exact for finite a + b: the TwoSum error has the
// sign of (a + b) - RN(a + b), and it is exactly representable (also for
// subnormal sums under gradual underflow).
double add_down(double a, double b) noexcept {
  const DoubleWord sum = two_sum(a, b);
  return sum.low < 0.0 ? next_down(sum.high) : sum.high;
}

double add_up(double a, double b) noexcept {
  const DoubleWord sum = two_sum(a, b);
  return sum.low > 0.0 ? next_up(sum.high) : sum.high;
}

// [lower, upper] containing every real within `bound` >= 0 of high + low.
Enclosure enclose(DoubleWord value, double bound) noexcept {
  return {add_down(value.high, add_down(value.low, -bound)),
          add_up(value.high, add_up(value.low, bound))};
}

// Upper bound of |value| * scale + absolute; scale is a power of two, so the
// product is exact whenever it is normal (the kernels guarantee it).
double error_bound(DoubleWord value, double scale, double absolute = 0.0) noexcept {
  return add_up(std::fabs(value.high) * scale, absolute);
}

DoubleWord horner(DoubleWord z, const DoubleWord* table, int first, int terms) noexcept {
  DoubleWord sum = table[first + terms - 1];
  for (int n = terms - 2; n >= 0; --n) sum = add(table[first + n], multiply(z, sum));
  return sum;
}

DoubleWord horner_stride(DoubleWord z, const DoubleWord* table, int first, int terms) noexcept {
  DoubleWord sum = table[first + 2 * (terms - 1)];
  for (int n = terms - 2; n >= 0; --n) sum = add(table[first + 2 * n], multiply(z, sum));
  return sum;
}

// Endpoint enclosures below 2^-27 in magnitude, from the alternating Taylor
// bounds |f(x) - x| <= |x|^3 / 3 (sin: /6), which lie strictly inside the gap
// between x and its binary64 neighbour toward zero (2^(2e+3) / 3 < 2^-53 for
// |x| < 2^(e+1) <= 2^-27). Signed zeros map to themselves.
Enclosure toward_zero(double x) noexcept {  // sin, atan, tanh: |f(x)| < |x|
  if (x > 0.0) return {next_down(x), x};
  if (x < 0.0) return {x, next_up(x)};
  return {x, x};
}

Enclosure away_from_zero(double x) noexcept {  // tan: |f(x)| > |x|
  if (x > 0.0) return {x, next_up(x)};
  if (x < 0.0) return {next_down(x), x};
  return {x, x};
}

constexpr double kTinyArgument = 0x1p-27;

// --------------------------------------------------------------------- exp
//
// Reduction: k = nearest integer to x RN(1/ln 2) (|k| <= 1076), r = x - k ln 2
// with ln 2 = L1 + L2 + L3 (+ < 2^-157.3). k L1 is exact (42-bit L1,
// |k| < 2^11); x - k L1 is exact because both are multiples of 2^-54 and the
// difference is below 1/2 in magnitude (|x| >= 0.34 when k != 0); k L2 and
// k L3 are exact TwoProducts. The low part ((s_l - p2_l) - p3_h) - p3_l has
// magnitude <= 2^-55.4 and three roundings, so the DW r = TwoSum(s_h, t)
// differs from x - k ln 2 by delta_r <= 3 2^-108.4 + 1076 2^-157.3 <= 2^-106.5,
// and |r| <= ln 2 (1/2 + 2^-41) <= rho = 0.3466.
// Approximation: sum_{n<=22} r^n / n!, Lagrange remainder
// rho^23 / 23! e^rho <= 2^-108.6 e^-rho (relative).
// Evaluation (Horner lemma, P = exp): 8.1u^2 (1 + rho) e^rho + 2^-107 e^rho;
// relative to e^r >= e^-rho: 21.8u^2 + 1.0u^2; with delta_r (1 + 2^-50) and
// the remainder the relative error is <= 24.1u^2 = 2^-101.4 < 2^-99 / 5.
// Scaling: e^x = e^r 2^k, applied to each outward endpoint by two exact
// power-of-two products; an inexact (subnormal) or overflowing product is
// detected by scaling back exactly and stepped outward.
constexpr double kInverseLn2 = 0x1.71547652b82fep0;
constexpr double kRoundingShift = 0x1.8p52;
constexpr int kExpTerms = 23;
constexpr double kExpBound = 0x1p-99;
constexpr double kExpOverflow = 709.79;    // > ln(DBL_MAX) = 709.7827128933840
constexpr double kExpUnderflow = -745.2;   // < ln(2^-1075) = -745.1332191019412

struct ScaledWord {
  DoubleWord value;  // e^r with relative error <= 24.1u^2
  int exponent;      // k
};

ScaledWord exp_reduced(double x) noexcept {  // x in [kExpUnderflow, kExpOverflow]
  const double k = (x * kInverseLn2 + kRoundingShift) - kRoundingShift;
  const double head = x - k * kLn2[0];
  const DoubleWord second = two_product(k, kLn2[1]);
  const DoubleWord third = two_product(k, kLn2[2]);
  const DoubleWord partial = two_sum(head, -second.high);
  const double tail = ((partial.low - second.low) - third.high) - third.low;
  const DoubleWord r = two_sum(partial.high, tail);
  return {horner(r, kInverseFactorial, 0, kExpTerms), static_cast<int>(k)};
}

double scaled(double value, int exponent) noexcept {  // RN(value 2^exponent), |exponent| <= 1077
  const int first = exponent / 2;
  return (value * power_of_two(first)) * power_of_two(exponent - first);
}

double scaled_down(double value, int exponent) noexcept {  // value in [1/2, 2]
  const double product = scaled(value, exponent);
  return scaled(product, -exponent) > value ? next_down(product) : product;
}

double scaled_up(double value, int exponent) noexcept {
  const double product = scaled(value, exponent);
  return scaled(product, -exponent) < value ? next_up(product) : product;
}

Enclosure exp_point(double x) noexcept {
  if (x == 0.0) return {1.0, 1.0};
  if (x > kExpOverflow) return {kLargest, kInfinity};
  if (x < kExpUnderflow) return {0.0, kSmallest};
  const ScaledWord reduced = exp_reduced(x);
  const Enclosure unit = enclose(reduced.value, error_bound(reduced.value, kExpBound));
  return {scaled_down(unit.lower, reduced.exponent), scaled_up(unit.upper, reduced.exponent)};
}

// --------------------------------------------------------------------- log
//
// Reduction: x = m 2^e exactly (subnormals prescaled by 2^54) with
// m in [RN(sqrt 2) / 2, RN(sqrt 2)], so log x = e ln 2 + 2 atanh(s) with
// s = (m - 1) / (m + 1), |s| <= rho_s = 0.17157288 (+ 2^-50 relative).
// m - 1 is exact (Sterbenz) and m + 1 is an exact TwoSum, so the DW division
// gives s with relative error <= 11.01u^2.
// Approximation: atanh(s) / s = sum_{n<=19} z^n / (2n + 1), z = s^2 <= 0.029438;
// remainder <= rho_z^20 / (41 (1 - rho_z)) <= 2^-107.0.
// Evaluation: z = multiply(s, s) has relative error <= 5u^2 + 2 11.01u^2;
// Horner (P(t) <= 1.0102, t P'(t) <= 0.0099, all terms positive): <= 8.3u^2,
// coefficients 0.5u^2, perturbation of z <= 0.3u^2; times s (5u^2) and the
// s error: log m has relative error <= 26u^2. e ln 2 = e (L1 + L2 + L3) is
// formed from exact products with three roundings of a <= |e| 2^-54 tail:
// relative error <= 2.2u^2. The final DW sum (<= 3.01u^2 of the result) can
// cancel at most to |e ln 2| - |log m| >= |e ln 2| / 2 (|e| = 1), so the total
// relative error is <= 3.01 + 2 (2.2) + 26 = 33.4u^2 = 2^-100.9 < 2^-98 / 7.
constexpr double kSquareRootTwo = 0x1.6a09e667f3bcdp0;  // RN(sqrt 2)
constexpr int kLogTerms = 20;
constexpr double kLogBound = 0x1p-98;

DoubleWord log_word(double x) noexcept {  // x > 0 finite
  int exponent = 0;
  if (x < 0x1p-1022) {
    x *= 0x1p54;
    exponent = -54;
  }
  const std::uint64_t bits = std::bit_cast<std::uint64_t>(x);
  exponent += static_cast<int>(bits >> 52) - 1023;
  double mantissa = std::bit_cast<double>((bits & kMantissaMask) | (std::uint64_t{1023} << 52));
  if (mantissa > kSquareRootTwo) {
    mantissa *= 0.5;
    exponent += 1;
  }
  const DoubleWord s = divide({mantissa - 1.0, 0.0}, two_sum(mantissa, 1.0));
  const DoubleWord series = horner(multiply(s, s), kInverseOdd, 0, kLogTerms);
  const DoubleWord half = multiply(s, series);
  const DoubleWord logarithm = {2.0 * half.high, 2.0 * half.low};
  const double e = exponent;
  const DoubleWord second = two_product(e, kLn2[1]);
  const DoubleWord third = two_product(e, kLn2[2]);
  const DoubleWord partial = two_sum(e * kLn2[0], second.high);
  const DoubleWord scale =
      two_sum(partial.high, ((partial.low + second.low) + third.high) + third.low);
  return add(scale, logarithm);
}

Enclosure log_point(double x) noexcept {  // x > 0
  if (x == kInfinity) return {kLargest, kInfinity};
  const DoubleWord value = log_word(x);
  return enclose(value, error_bound(value, kLogBound));
}

// ------------------------------------------------------- sin, cos and tan
//
// Reduction (every finite x): x (2/pi) = 4n + q + f with q in {0, 1, 2, 3} and
// |f| <= 1/2, r = f pi/2.
//  * |x| <= RN(pi/4) < pi/4: q = 0, r = x exactly.
//  * otherwise Payne-Hanek: x = M 2^E (53-bit M). Words of 2/pi whose
//    products with M are multiples of 4 are skipped; the next five words are
//    multiplied exactly into a 384-bit fixed-point sum, so the dropped tail is
//    below M 2^(E - 64 i0 - 320) < 2^-201 quadrant units. The integer part
//    mod 4 and the rounded fraction are exact; the fraction's magnitude is
//    converted from its leading five 32-bit chunks by DWPlusFP (relative
//    <= 3 2u^2 + 2^-128 <= 6.1u^2), and r = multiply(f, pi/2) has relative
//    error <= 6.1u^2 + 5u^2 + 2^-109.7 <= 11.2u^2 plus the absolute tail
//    < 2^-201 pi/2 < 2^-199.3 (bounded by 2^-199 below). A nonzero fraction is
//    at least 2^-384, so |r| > 2^-384 and no later operation underflows.
// Approximation, |r| <= rho = 0.785399:
//  sin r = r S(r^2), S = sum_{n<=13} (-z)^n / (2n+1)!, remainder
//    rho^28 / 29! / S_min <= 2^-112.4 with S_min = sin(rho)/rho >= 0.9003;
//  cos r = C(r^2), C = sum_{n<=13} (-z)^n / (2n)!, remainder
//    rho^28 / 28! / C_min <= 2^-107.2 with C_min = cos(rho) >= 0.7071.
// Evaluation (Horner lemma with P(t) = sinh(sqrt t)/sqrt t <= 1.1078,
// t P' <= 0.1084 for S; cosh(sqrt t) <= 1.3246, t P' <= 0.3411 for C):
//  sin: 11.2 (r) + 0.57 (z = r^2, 5u^2) + 10.94 (Horner) + 0.62 (coefficients)
//       + 5 (r S) = 28.3u^2 = 2^-101.2 < 2^-98 / 9, plus 2^-199 absolute;
//  cos: 8.8 (r) + 2.18 (z) + 19.1 (Horner) + 0.94 (coefficients) = 31u^2
//       = 2^-101.05 < 2^-98 / 8, plus 2^-199 absolute;
//  tan = sin/cos (q even) or -cos/sin (q odd): 28.3 + 31 + 11.01 = 70.3u^2
//       = 2^-99.9 < 2^-97 / 7, plus the absolute tail times
//       |d tan/dr| <= 1 + tan^2, bounded by 2^-198 (1 + value^2).
// Arguments below 2^-27 use the toward_zero / away_from_zero bounds, cos the
// bound 1 - x^2 / 2 > 1 - 2^-53.
// Extremum and pole decisions use the exact quadrant and the sign of the
// fraction: on the direct path the computed fraction RN(x RN(2/pi)) has the
// exact sign of x; on the Payne-Hanek path the fraction is known to within
// 6.1u^2 relative plus 2^-200 absolute, so a sign is trusted only beyond
// 2^-199. Undecided means contained.
constexpr double kQuarterPi = 0x1.921fb54442d18p-1;  // RN(pi/4) < pi/4
constexpr double kTwoOverPiRounded = 0x1.45f306dc9c883p-1;  // RN(2/pi)
constexpr int kTrigonometricTerms = 14;
constexpr double kSineBound = 0x1p-98;
constexpr double kTangentBound = 0x1p-97;
constexpr double kArgumentTail = 0x1p-199;
constexpr double kFractionMargin = 0x1p-199;
constexpr double kWidestReduced = 7.0;  // > 2 pi; wider boxes are full range

struct Reduction {
  int quadrant;
  DoubleWord fraction;  // f in quadrant units
  DoubleWord argument;  // r = f pi/2
  double margin;        // a fraction sign is decided only beyond this margin
  double tail;          // absolute error of r beyond its relative bound
};

void multiply_words(std::uint64_t a, std::uint64_t b, std::uint64_t& high,
                    std::uint64_t& low) noexcept {
  const std::uint64_t a0 = a & 0xFFFFFFFFu, a1 = a >> 32;
  const std::uint64_t b0 = b & 0xFFFFFFFFu, b1 = b >> 32;
  const std::uint64_t p00 = a0 * b0, p01 = a0 * b1, p10 = a1 * b0, p11 = a1 * b1;
  const std::uint64_t middle = (p00 >> 32) + (p01 & 0xFFFFFFFFu) + (p10 & 0xFFFFFFFFu);
  low = (middle << 32) | (p00 & 0xFFFFFFFFu);
  high = p11 + (p01 >> 32) + (p10 >> 32) + (middle >> 32);
}

constexpr int kLimbs = 6;  // 384-bit fixed point, least significant limb first

void accumulate(std::uint64_t* sum, int limb, std::uint64_t value) noexcept {
  for (int index = limb; index < kLimbs && value != 0; ++index) {
    sum[index] += value;
    value = sum[index] < value ? 1 : 0;
  }
}

std::uint64_t bit_at(const std::uint64_t* sum, int position) noexcept {
  return (sum[position / 64] >> (position % 64)) & 1u;
}

// Payne-Hanek reduction of magnitude > RN(pi/4), finite.
Reduction reduce_large(double magnitude) noexcept {
  const std::uint64_t bits = std::bit_cast<std::uint64_t>(magnitude);
  const std::uint64_t mantissa = (bits & kMantissaMask) | (std::uint64_t{1} << 52);
  const int exponent = static_cast<int>(bits >> 52) - 1075;  // magnitude = mantissa 2^exponent
  const int first = exponent >= 66 ? (exponent - 66) / 64 + 1 : 0;
  std::uint64_t sum[kLimbs] = {};
  for (int word = 0; word < 5; ++word) {
    std::uint64_t high = 0;
    std::uint64_t low = 0;
    multiply_words(mantissa, kTwoOverPi[first + word], high, low);
    accumulate(sum, 4 - word, low);
    accumulate(sum, 5 - word, high);
  }
  // sum 2^-point is x (2/pi) mod 4 up to the dropped tail; point in [255, 373].
  const int point = 320 + 64 * first - exponent;
  int quadrant = static_cast<int>(bit_at(sum, point) | (bit_at(sum, point + 1) << 1));
  const bool round_up = bit_at(sum, point - 1) != 0;
  for (int limb = 0; limb < kLimbs; ++limb) {  // keep the fraction bits
    const int low_bit = 64 * limb;
    if (low_bit >= point) {
      sum[limb] = 0;
    } else if (point - low_bit < 64) {
      sum[limb] &= (std::uint64_t{1} << (point - low_bit)) - 1;
    }
  }
  if (round_up) {  // fraction - 1: magnitude 2^point - F, quadrant + 1
    quadrant = (quadrant + 1) & 3;
    std::uint64_t carry = 1;
    for (int limb = 0; limb < kLimbs; ++limb) {
      const std::uint64_t value = ~sum[limb] + carry;
      carry = (carry != 0 && value == 0) ? 1 : 0;
      sum[limb] = value;
    }
    for (int limb = 0; limb < kLimbs; ++limb) {
      const int low_bit = 64 * limb;
      if (low_bit >= point) {
        sum[limb] = 0;
      } else if (point - low_bit < 64) {
        sum[limb] &= (std::uint64_t{1} << (point - low_bit)) - 1;
      }
    }
  }
  // Align the binary point to bit 384: aligned 2^-384 is |fraction|.
  const int shift = 384 - point;  // in [11, 129]
  const int word_shift = shift / 64;
  const int bit_shift = shift % 64;
  std::uint64_t aligned[kLimbs] = {};
  for (int limb = kLimbs - 1; limb >= 0; --limb) {
    const int source = limb - word_shift;
    if (source < 0) continue;
    std::uint64_t value = sum[source] << bit_shift;
    if (bit_shift != 0 && source >= 1) value |= sum[source - 1] >> (64 - bit_shift);
    aligned[limb] = value;
  }
  std::uint32_t chunks[2 * kLimbs];
  for (int chunk = 0; chunk < 2 * kLimbs; ++chunk) {
    const std::uint64_t limb = aligned[kLimbs - 1 - chunk / 2];
    chunks[chunk] = static_cast<std::uint32_t>(chunk % 2 == 0 ? limb >> 32 : limb);
  }
  int leading = 0;
  while (leading < 2 * kLimbs && chunks[leading] == 0) ++leading;
  DoubleWord fraction = {0.0, 0.0};
  if (leading < 2 * kLimbs) {
    const auto term = [&](int chunk) {
      return chunk < 2 * kLimbs ? static_cast<double>(chunks[chunk]) * power_of_two(-32 * (chunk + 1))
                                : 0.0;
    };
    fraction = two_sum(term(leading), term(leading + 1));
    for (int chunk = leading + 2; chunk < leading + 5; ++chunk) fraction = add(fraction, term(chunk));
  }
  if (round_up) fraction = negate(fraction);
  return {quadrant, fraction, multiply(fraction, kHalfPi), kFractionMargin, kArgumentTail};
}

Reduction reduce(double x) noexcept {  // x finite
  if (std::fabs(x) <= kQuarterPi) return {0, {x * kTwoOverPiRounded, 0.0}, {x, 0.0}, 0.0, 0.0};
  const Reduction magnitude = reduce_large(std::fabs(x));
  if (x > 0.0) return magnitude;
  return {(4 - magnitude.quadrant) & 3, negate(magnitude.fraction), negate(magnitude.argument),
          magnitude.margin, magnitude.tail};
}

DoubleWord sine_word(DoubleWord r) noexcept {
  const DoubleWord z = negate(multiply(r, r));
  return multiply(r, horner_stride(z, kInverseFactorial, 1, kTrigonometricTerms));
}

DoubleWord cosine_word(DoubleWord r) noexcept {
  const DoubleWord z = negate(multiply(r, r));
  return horner_stride(z, kInverseFactorial, 0, kTrigonometricTerms);
}

// Enclosure of f(x) for the reduced endpoint x; tan requires that no pole is
// possible at x (a quadrant-odd fraction beyond the sign margin).
Enclosure periodic_point(Function function, double x, const Reduction& reduced) noexcept {
  if (std::fabs(x) < kTinyArgument) {
    switch (function) {
      case Function::kSin:
        return toward_zero(x);
      case Function::kCos:
        return x == 0.0 ? Enclosure{1.0, 1.0} : Enclosure{next_down(1.0), 1.0};
      default:
        return away_from_zero(x);
    }
  }
  const int quadrant = reduced.quadrant;
  if (function == Function::kTan) {
    const DoubleWord sine = sine_word(reduced.argument);
    const DoubleWord cosine = cosine_word(reduced.argument);
    const DoubleWord value =
        quadrant % 2 == 0 ? divide(sine, cosine) : negate(divide(cosine, sine));
    const double slope = reduced.tail == 0.0 ? 0.0
                                             : add_up(1.0, value.high * value.high) * 2.0;
    return enclose(value, error_bound(value, kTangentBound, reduced.tail * slope));
  }
  // sin x = sin r, cos r, -sin r, -cos r and cos x = cos r, -sin r, -cos r, sin r
  // for q = 0, 1, 2, 3.
  const int phase = function == Function::kSin ? quadrant : (quadrant + 1) & 3;
  DoubleWord value = phase % 2 == 0 ? sine_word(reduced.argument) : cosine_word(reduced.argument);
  if (phase >= 2) value = negate(value);
  return enclose(value, error_bound(value, kSineBound, reduced.tail));
}

double ieee_minimum(double a, double b) noexcept {
  if (a < b) return a;
  if (b < a) return b;
  return std::signbit(a) ? a : b;
}

double ieee_maximum(double a, double b) noexcept {
  if (a > b) return a;
  if (b > a) return b;
  return std::signbit(a) ? b : a;
}

Enclosure periodic(Function function, double lower, double upper) noexcept {
  const bool tangent = function == Function::kTan;
  const Enclosure full = tangent ? kWholeLine : kUnitRange;
  if (std::isnan(lower) || std::isnan(upper)) return kWholeLine;
  if (!(lower <= upper) || !std::isfinite(lower) || !std::isfinite(upper)) return full;
  const double width = upper - lower;  // RN(width) > 7 implies width > 7 > 2 pi
  if (!(width <= kWidestReduced)) return full;
  const Reduction first = reduce(lower);
  const Reduction last = lower == upper ? first : reduce(upper);
  // Lift the upper quadrant by whole periods: the true value of `periods` is
  // within 1e-14 of the integer n_upper - n_lower, so rounding recovers it.
  const double periods =
      0.25 * (width * kTwoOverPiRounded -
              (static_cast<double>(last.quadrant - first.quadrant) +
               (last.fraction.high - first.fraction.high)));
  const int top = last.quadrant + 4 * (static_cast<int>(periods + 8.5) - 8);
  bool maximum = false;
  bool minimum = false;
  for (int point = first.quadrant; point <= top; ++point) {
    if (point == first.quadrant && !(first.fraction.high <= first.margin)) continue;
    if (point == top && !(last.fraction.high >= -last.margin)) continue;
    const int phase = point & 3;
    switch (function) {
      case Function::kSin:
        maximum = maximum || phase == 1;
        minimum = minimum || phase == 3;
        break;
      case Function::kCos:
        maximum = maximum || phase == 0;
        minimum = minimum || phase == 2;
        break;
      default:
        if (phase % 2 == 1) return full;
        break;
    }
  }
  const Enclosure at_lower = periodic_point(function, lower, first);
  const Enclosure at_upper = lower == upper ? at_lower : periodic_point(function, upper, last);
  if (tangent) return {at_lower.lower, at_upper.upper};
  const double low = minimum ? -1.0 : ieee_minimum(at_lower.lower, at_upper.lower);
  const double high = maximum ? 1.0 : ieee_maximum(at_lower.upper, at_upper.upper);
  return {ieee_maximum(low, -1.0), ieee_minimum(high, 1.0)};
}

// -------------------------------------------------------------------- atan
//
// atan(-x) = -atan(x). For t = |x| <= 1: j = nearest integer to 16 t,
// c = j/16 (exact), z = (t - c) / (1 + t c), |z| <= 1/32 + 2^-50, and
// atan t = atan(c) + atan(z) with the tabulated DW atan(c). For 1 < t <= 2^60,
// atan t = pi/2 - atan(1/t) with 1/t from the DW division (11.01u^2, which
// propagates with condition t / ((1 + t^2) atan t) <= 1). For t > 2^60,
// atan t in (pi/2 - 2^-60, pi/2); atan(+inf) = pi/2.
// Approximation: atan z = z A(z^2), A = sum_{n<=10} (-w)^n / (2n+1),
// remainder (alternating, decreasing) <= rho_w^11 / 23 <= 2^-114.5.
// Evaluation: z has relative error <= 2 (t - c) + 2 + 2 (1 + t c) + 11.01
// (division) = 17u^2; w = z^2: 5 + 34 = 39u^2 (perturbs A by <= 0.02u^2);
// Horner (A <= 1.0003): 8.1u^2; coefficients 0.5u^2; z A: 5u^2; so atan z
// carries <= 33u^2. atan(c) + atan(z) (DW sum 3.01u^2) cancels at most to half
// of atan(c) (j >= 1, |atan z| <= atan(1/32)): <= 3.01 + 33 + 2 (0.5) = 37u^2.
// With 12u^2 for 1/t and the final pi/2 - atan(1/t) (result >= pi/4, 3.01u^2
// + 2 2^-109.7): <= 52.3u^2 = 2^-100.3 < 2^-98 / 4.
constexpr int kArctangentTerms = 11;
constexpr double kArctangentBound = 0x1p-98;

DoubleWord arctangent_unit(DoubleWord t) noexcept {  // t in [0, 1]
  const int index = static_cast<int>(16.0 * t.high + 0.5);
  const double center = 0.0625 * index;
  const DoubleWord z = divide(add(t, -center), add(multiply(t, center), 1.0));
  const DoubleWord w = negate(multiply(z, z));
  return add(kArctangent[index], multiply(z, horner(w, kInverseOdd, 0, kArctangentTerms)));
}

Enclosure atan_point(double x) noexcept {
  const double magnitude = std::fabs(x);
  if (magnitude < kTinyArgument) return toward_zero(x);
  Enclosure result;
  if (magnitude == kInfinity) {
    result = enclose(kHalfPi, 0x1p-108);
  } else if (magnitude > 0x1p60) {
    result = enclose(kHalfPi, 0x1p-59);
  } else {
    const DoubleWord value =
        magnitude > 1.0
            ? add(kHalfPi, negate(arctangent_unit(divide({1.0, 0.0}, {magnitude, 0.0}))))
            : arctangent_unit({magnitude, 0.0});
    result = enclose(value, error_bound(value, kArctangentBound));
  }
  return x < 0.0 ? negate(result) : result;
}

// -------------------------------------------------------------------- tanh
//
// tanh(-x) = -tanh(x) and tanh(+inf) = 1 exactly. For finite a = |x| >= 20,
// 1 - tanh a = 2 / (e^(2a) + 1)
// <= 8.5e-18 < 2^-53, so tanh a in [1 - 2^-53, 1]. Otherwise with y = -2a
// (exact) and E = expm1(y) in (-1, 0): tanh a = -E / (2 + E).
// expm1, y >= -rho (rho = 0.3466): E = y Q(y), Q = sum_{n<=21} y^n / (n+1)!,
// Lagrange remainder rho^22 / 23! e^rho / Q_min <= 2^-107.3 with
// Q_min = (1 - e^-rho)/rho >= 0.8451; Horner (P(t) = (e^t - 1)/t <= 1.1949,
// t P' <= 0.2192): 11.5u^2 / Q_min = 13.6u^2, coefficients 0.7u^2, times y
// (multiply by a binary64, 2u^2): E carries <= 16.3u^2.
// expm1, y < -rho: E = e^y - 1 from the exp reduction (24.1u^2, exact 2^k
// scaling of both words, k >= -58) and DWPlusFP (2u^2): the cancellation
// factor e^y / |E| <= 2.415 gives <= 60.2u^2.
// tanh: numerator E, denominator 2 + E (DWPlusFP, its relative error
// <= 2u^2 + |E| / (2 + E) eps_E <= 2u^2 + eps_E), DW division 11.01u^2:
// <= 2 eps_E + 13.01u^2 <= 133.5u^2 = 2^-98.9 < 2^-96 / 3.
constexpr double kExpm1Switch = -0.3466;
constexpr int kExpm1Terms = 22;
constexpr double kHyperbolicTangentBound = 0x1p-96;
constexpr double kSaturation = 20.0;

Enclosure tanh_point(double x) noexcept {
  const double magnitude = std::fabs(x);
  if (magnitude < kTinyArgument) return toward_zero(x);
  Enclosure result;
  if (magnitude == kInfinity) {
    result = {1.0, 1.0};
  } else if (magnitude >= kSaturation) {
    result = {next_down(1.0), 1.0};
  } else {
    const double y = -2.0 * magnitude;
    DoubleWord expm1;
    if (y >= kExpm1Switch) {
      expm1 = multiply(horner({y, 0.0}, kInverseFactorial, 1, kExpm1Terms), y);
    } else {
      const ScaledWord reduced = exp_reduced(y);
      const double scale = power_of_two(reduced.exponent);
      expm1 = add(DoubleWord{reduced.value.high * scale, reduced.value.low * scale}, -1.0);
    }
    const DoubleWord value = divide(negate(expm1), add(expm1, 2.0));
    result = enclose(value, error_bound(value, kHyperbolicTangentBound));
  }
  return x < 0.0 ? negate(result) : result;
}

// -------------------------------------------------------------- asin, acos
//
// Square root of a DW d >= 0: s0 = RN(sqrt(d_h)) (correctly rounded), one
// Newton correction c = RN(R_h / (2 s0)) with R = d - s0^2 (exact TwoProduct,
// AccurateDWPlusDW). |s0 - sqrt d| <= 1.5u sqrt d, so the exact Newton step errs
// by <= (1.5u)^2 / 2 = 1.13u^2 and the rounded correction by <= 2u |c|
// <= 3u^2 (relative to sqrt d): relative error <= 4.2u^2 plus half of d's own.
//
// arcsine_core(z), z in [0, 1/2] (a DW): asin z = atan(z / sqrt(1 - z^2)) with
// t = z / sqrt(1 - z^2) in [0, 0.5774] and the atan unit kernel (37u^2). For a
// binary64 z: 1 - z^2 from an exact TwoProduct and AccurateDWPlusDW (3u^2, the
// result >= 3/4), sqrt 4.2 + 1.5u^2, division 11.01u^2: t carries <= 19.8u^2;
// for z = sqrt(y) (4.2u^2): z^2 carries 5 + 8.4u^2 on a value <= 1/4, so
// 1 - z^2 carries <= 3 + 3.4u^2, sqrt 4.2 + 3.2u^2, and t <= 4.2 + 7.4 + 11.01
// = 22.7u^2. asin's condition z / (sqrt(1 - z^2) asin z) is at most 1.11 on
// [0, 1/2] and atan's t / ((1 + t^2) atan t) at most 1, so asin z carries
// <= 37 + 1.11 (22.7) = 62.2u^2.
// asin x (asin(-x) = -asin x): |x| < 2^-27 uses away_from_zero (asin x - x
// <= 0.17 |x|^3, inside the gap above |x|); |x| <= 1/2 the core on z = |x|
// (<= 59u^2); |x| > 1/2: asin |x| = pi/2 - 2 asin(sqrt((1 - |x|) / 2)) with
// 1 - |x| exact (Sterbenz) and the halving exact, z in [0, 1/2]; the result
// >= pi/6 bounds the cancellation: 3.01 + 2 (62.2) + 3 (2^-109.7 / u^2)
// <= 128u^2.
// acos x: |x| <= 1/2: pi/2 - asin x (result >= pi/3, asin x / result <= 1/2):
// <= 3.01 + 0.5 (59) + 1.5 (0.08) <= 33u^2; x > 1/2: 2 asin(sqrt((1 - x)/2))
// <= 62.2u^2; x < -1/2: pi - 2 asin(sqrt((1 + x)/2)) (result >= 2pi/3):
// <= 3.01 + 62.2 + 0.08 <= 66u^2. pi = 2 (pi/2 DW) exactly.
// All cases: <= 128u^2 = 2^-99 < 2^-96 / 8. Underflowing products for tiny z
// add absolute errors below 2^-1070, absorbed by the margin (acos >= pi/3 and
// tiny asin takes the away_from_zero path). Exact results: asin(+-0) = +-0,
// acos(1) = 0 (the core returns exactly 0 for z = 0); asin(+-1), acos(0),
// acos(-1) are pi/2, pi/2, pi enclosed through the bound.
constexpr double kArcsineBound = 0x1p-96;

DoubleWord square_root(DoubleWord d) noexcept {  // d >= 0
  if (d.high == 0.0) return {0.0, 0.0};
  const double first = std::sqrt(d.high);
  const DoubleWord remainder = add(d, negate(two_product(first, first)));
  return fast_two_sum(first, remainder.high / (2.0 * first));
}

DoubleWord arcsine_core(DoubleWord z) noexcept {  // z in [0, 1/2]
  const DoubleWord complement = add(DoubleWord{1.0, 0.0}, negate(multiply(z, z)));
  return arctangent_unit(divide(z, square_root(complement)));
}

// asin(sqrt((1 - m) / 2)) for m in (1/2, 1]: 1 - m is exact (Sterbenz).
DoubleWord arcsine_half_complement(double magnitude) noexcept {
  return arcsine_core(square_root({0.5 * (1.0 - magnitude), 0.0}));
}

DoubleWord twice(DoubleWord x) noexcept { return {2.0 * x.high, 2.0 * x.low}; }

Enclosure asin_point(double x) noexcept {  // x in [-1, 1]
  const double magnitude = std::fabs(x);
  if (magnitude < kTinyArgument) return away_from_zero(x);
  const DoubleWord value =
      magnitude <= 0.5 ? arcsine_core({magnitude, 0.0})
                       : add(kHalfPi, negate(twice(arcsine_half_complement(magnitude))));
  const Enclosure result = enclose(value, error_bound(value, kArcsineBound));
  return x < 0.0 ? negate(result) : result;
}

Enclosure acos_point(double x) noexcept {  // x in [-1, 1]
  const double magnitude = std::fabs(x);
  DoubleWord value;
  if (magnitude <= 0.5) {
    const DoubleWord arcsine = arcsine_core({magnitude, 0.0});
    value = add(kHalfPi, x < 0.0 ? arcsine : negate(arcsine));
  } else if (x > 0.0) {
    value = twice(arcsine_half_complement(magnitude));
  } else {
    value = add(twice(kHalfPi), negate(twice(arcsine_half_complement(magnitude))));
  }
  return enclose(value, error_bound(value, kArcsineBound));
}

